#!/usr/bin/env bash
set -euo pipefail
usage() { echo "Usage: $0 prepare-source-release|prepare-final-assets --input DIR --version X.Y.Z --output DIR [--public-source-url URL]" >&2; exit 2; }
phase="${1:-}"; shift || true
input= output= version= public_url=
while [ "$#" -gt 0 ]; do case "$1" in --input) input="$2"; shift 2;; --output) output="$2"; shift 2;; --version) version="$2"; shift 2;; --public-source-url) public_url="$2"; shift 2;; *) usage;; esac; done
case "$version" in [0-9]*.[0-9]*.[0-9]*) ;; *) usage;; esac; [ -d "$input" ] && [ -n "$output" ] || usage
source="$(find "$input" -type f -name "proxor-$version.tar.gz" -print -quit)"; manifest="$(find "$input" -type f -name "proxor-$version.source-manifest" -print -quit)"
[ -n "$source" ] && [ -n "$manifest" ] || { echo 'verified source artifact is required' >&2; exit 1; }
sha="$(shasum -a 256 "$source" | awk '{print $1}')"; grep -qx "version=$version" "$manifest"; grep -qx "sha256=$sha" "$manifest"
mkdir -p "$output"; cp "$source" "$manifest" "$output/"
if [ "$phase" = prepare-source-release ]; then exit 0; fi
[ "$phase" = prepare-final-assets ] || usage
case "$public_url" in "https://github.com/Ogstra/proxor/releases/download/"*/"proxor-$version.tar.gz") ;; *) echo 'public source URL must be the attached release asset' >&2; exit 1;; esac
for required in '*-windows64.zip' '*-winget-x64.zip' '*.AppImage' '*.deb' '*.rpm' '*.flatpak'; do find "$input" -type f -name "$required" -print -quit | grep -q . || { echo "missing $required" >&2; exit 1; }; done
! find "$input" -type f \( -iname '*.msi' -o -iname '*.dmg' \) -print -quit | grep -q .
# Only what a user downloads and runs: debug symbols, debug packages and source RPMs
# stay build artifacts, because a release list full of them hides the actual downloads.
assets() { find "$input" -type f \( -name '*.zip' -o -name '*.AppImage' -o -name '*.deb' -o -name '*.rpm' -o -name '*.flatpak' \) ! -name '*-symbols.zip' ! -name '*-debuginfo-*' ! -name '*-debugsource-*' ! -name '*.src.rpm'; }
asset_names() { assets | while read -r asset; do basename "$asset"; done; }
# Only the files that become release assets have to be unique: the build artifacts
# also carry per-job intermediates that legitimately share a name.
duplicates="$(asset_names | sort | uniq -d)"
[ -z "$duplicates" ] || { printf 'duplicate release asset names:\n%s\n' "$duplicates" >&2; exit 1; }
winget="$(find "$input" -type f -name '*-winget-x64.zip' -print -quit)"; winget_sha="$(shasum -a 256 "$winget"|awk '{print $1}')"
tag="${public_url#https://github.com/Ogstra/proxor/releases/download/}"; tag="${tag%%/*}"
# The AUR and winget recipes are inputs for those package repositories, not downloads
# for users, so they are staged outside the published set.
recipes="$output/recipes"
packaging/winget/render-manifest.sh --version "$version" --url "https://github.com/Ogstra/proxor/releases/download/$tag/proxor-$version-winget-x64.zip" --sha256 "$winget_sha" --output "$recipes/winget-manifests"
pkgbuild="$(find "$input" -type f -name PKGBUILD -print -quit)"; srcinfo="$(find "$input" -type f -name .SRCINFO -print -quit)"
# .SRCINFO is generated by makepkg, which only exists in the Arch container that built
# and validated the recipe, so the release reuses that artifact instead of re-rendering.
[ -n "$pkgbuild" ] && [ -n "$srcinfo" ] || { echo 'validated AUR recipe is required' >&2; exit 1; }
for recipe in "$pkgbuild" "$srcinfo"; do grep -Fq "$public_url" "$recipe" && grep -Fq "$sha" "$recipe"; done
mkdir -p "$recipes/aur"; cp "$pkgbuild" "$srcinfo" "$recipes/aur/"
# The manifest records the submodule commits of the archive for packagers, so it travels
# with the recipes rather than with the downloads.
mv "$output/proxor-$version.source-manifest" "$recipes/"
assets | while read -r asset; do cp "$asset" "$output/"; done
test "$(find "$output" -type f \( -name '*.zip' -o -name '*.AppImage' -o -name '*.deb' -o -name '*.rpm' -o -name '*.flatpak' \) | wc -l)" -eq "$(asset_names | wc -l)"
(cd "$output" && find . -maxdepth 1 -type f ! -name SHA256SUMS -print0 | sort -z | xargs -0 shasum -a 256 > SHA256SUMS && shasum -a 256 -c SHA256SUMS)
